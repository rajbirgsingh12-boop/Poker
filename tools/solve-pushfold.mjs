// Solves heads-up push/fold for a grid of stack sizes and writes js/data/pushfold.js.
//
//   node tools/solve-pushfold.mjs
//
// Requires js/data/equity.js (see tools/build-equity.mjs).
import { writeFileSync } from 'node:fs';
import { fileURLToPath } from 'node:url';
import '../js/core.js';
import '../js/solver.js';
import '../js/data/equity.js';

const { core, solver, equityUpper } = globalThis.GTO;
const eq = core.decodeEquity(equityUpper);
const weights = solver.buildWeights(core);

const stacks = [];
for (let s = 1; s <= 25; s += 0.5) stacks.push(s);

const round = (x, d) => Number(x.toFixed(d));
const push = {}, call = {}, pushEV = {}, callEV = {};
let worst = 0;
for (const stack of stacks) {
  const res = solver.solvePushFold({ stack, eq, weights, iterations: 6000 });
  push[stack] = Array.from(res.push, (x) => round(x, 3));
  call[stack] = Array.from(res.call, (x) => round(x, 3));
  pushEV[stack] = Array.from(res.pushEV, (x) => round(x, 2));
  callEV[stack] = Array.from(res.callEV, (x) => round(x, 2));
  worst = Math.max(worst, res.exploitability);
  console.log(
    `${String(stack).padStart(4)}bb  push ${(solver.rangeShare(res.push, core) * 100).toFixed(1).padStart(5)}%` +
      `  call ${(solver.rangeShare(res.call, core) * 100).toFixed(1).padStart(5)}%` +
      `  SB EV ${res.value.toFixed(4)}  exploitability ${res.exploitability.toExponential(2)}`,
  );
}

const fmt = (obj) =>
  '{\n' + Object.entries(obj).map(([k, v]) => `    "${k}": [${v.join(',')}]`).join(',\n') + '\n  }';

const out = `/*
 * Heads-up push/fold Nash equilibria (no ante), generated by
 * tools/solve-pushfold.mjs with CFR+. Do not edit by hand.
 *
 * push[stack][hand]   - small blind shove frequency
 * call[stack][hand]   - big blind call frequency facing the shove
 * pushEV[stack][hand] - small blind EV of shoving, in bb (folding is -0.5)
 * callEV[stack][hand] - big blind EV of calling minus folding, in bb
 * Worst exploitability across all stacks: ${worst.toExponential(2)} bb/hand.
 */
(function (root) {
  root.GTO = root.GTO || {};
  root.GTO.pushfold = {
  stacks: [${stacks.join(',')}],
  push: ${fmt(push)},
  call: ${fmt(call)},
  pushEV: ${fmt(pushEV)},
  callEV: ${fmt(callEV)},
  };
})(typeof window !== 'undefined' ? window : globalThis);
`;

const dest = fileURLToPath(new URL('../js/data/pushfold.js', import.meta.url));
writeFileSync(dest, out);
console.log(`wrote ${dest} (${(out.length / 1024).toFixed(0)} KB)`);
